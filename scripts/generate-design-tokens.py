"""Generate WPF palette constants from the reviewed design specification. No app execution."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
tokens = json.loads((root / 'docs/design/visual-tokens.json').read_text())
roles = {
    'Bg': 'canvas', 'Surface': 'surface', 'Surface2': 'subtle', 'Surface3': 'subtle',
    'Accent': 'accent', 'AccentHover': 'accentHover', 'AccentPressed': 'accentPressed',
    'AccentText': 'onAccent', 'Selection': 'selection', 'Border': 'divider',
    'ControlBorder': 'controlBorder', 'NeutralBg': 'disabledSurface',
    'Text': 'text', 'Muted': 'secondaryText', 'Success': 'success',
    'SuccessSurface': 'successSurface', 'Warning': 'warning', 'WarningSurface': 'warningSurface',
    'Danger': 'danger', 'DangerSurface': 'dangerSurface', 'Link': 'accent', 'Focus': 'focus',
}
rows = [f'        ("{key}", "{tokens["themes"]["light"][role]}", "{tokens["themes"]["dark"][role]}"),' for key, role in roles.items()]
source = '// Generated by scripts/generate-design-tokens.py. Edit docs/design/visual-tokens.json.\nnamespace AlpWareStudio.Localay;\n\ninternal static class DesignTokens\n{\n    internal static readonly (string Name, string Light, string Dark)[] Palette =\n    [\n' + '\n'.join(rows) + '\n    ];\n}\n'
(root / 'src/DesignTokens.cs').write_text(source)
# Keep the pre-initialization light palette consistent with the generated runtime palette.
app_path = root / 'src/App.xaml'
app = app_path.read_text()
for name, role in roles.items():
    color = tokens['themes']['light'][role]
    app = re.sub(r'(<Color x:Key="' + name + r'Color">)[^<]+(</Color>)', lambda m: m[1] + color + m[2], app)
    app = re.sub(r'(<SolidColorBrush x:Key="' + name + r'Brush" Color=")[^"]+("\s*/>)', lambda m: m[1] + color + m[2], app)
app_path.write_text(app)
print('Generated palette constants only; Localay was not built or started.')
